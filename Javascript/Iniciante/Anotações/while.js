let senha = "";
let tentativas = 0;

while (senha !== "1234" && tentaivas <3){
    tentativas++;
}

/*

O que cada linha faz:

let senha = ""; → Cria uma variável chamada senha e atribui-lhe um valor vazio ("").

let tentativas = 0; → Cria uma variável para contar quantas tentativas foram feitas, começando em 0.

while (senha !== "1234" && tentaivas < 3) → É um ciclo de repetição (while). Significa: "Enquanto a senha for diferente de "1234" E o número de tentativas for menor que 3, faz..."

tentativas++; → Aumenta o contador de tentativas em +1 a cada volta do ciclo.

*/